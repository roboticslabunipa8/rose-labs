function prepareEntranceStaging(scope = document) {
  if (!isHomePage) return;

  entranceRevealSelectors.forEach((selector) => {
    scope.querySelectorAll(selector).forEach((item) => {
      item.classList.add("reveal");
    });
  });

  entranceChildGroups.forEach(({ selector, className, step }) => {
    scope.querySelectorAll(selector).forEach((container) => {
      const children = Array.from(container.children).filter(
        (child) => child instanceof HTMLElement && !child.classList.contains("section-parallax")
      );

      children.forEach((child, index) => {
        child.classList.add(className);
        child.style.setProperty("--reveal-delay", `${Math.min(index * step, 720)}ms`);
      });
    });
  });
}

let revealObserver = null;
let revealSequenceStarted = false;

function observeRevealItems(scope = document) {
  if (!isHomePage) return;

  const revealItems = scope.querySelectorAll(".reveal:not([data-reveal-observed])");
  if (!revealItems.length) return;

  if ("IntersectionObserver" in window) {
    if (!revealObserver) {
      revealObserver = new IntersectionObserver(
        (entries) => {
          entries.forEach((entry) => {
            if (entry.isIntersecting) {
              entry.target.classList.add("is-visible");
              revealObserver?.unobserve(entry.target);
            }
          });
        },
        { threshold: 0.15 }
      );
    }

    revealItems.forEach((item) => {
      item.dataset.revealObserved = "1";
      revealObserver.observe(item);
    });
    return;
  }

  revealItems.forEach((item) => {
    item.dataset.revealObserved = "1";
    item.classList.add("is-visible");
  });
}

function refreshRevealSequence(scope = document) {
  if (!isHomePage) return;

  prepareEntranceStaging(scope);
  if (revealSequenceStarted) {
    observeRevealItems(scope);
  }
}

function startRevealSequence() {
  if (!isHomePage) return;

  if (revealSequenceStarted) return;
  revealSequenceStarted = true;
  observeRevealItems();
}

function updateHeroOrbitMotion() {
  if (!heroOrbitTrack || !heroOrbitSection) return;

  const cards = heroOrbitTrack.querySelectorAll(".hero-orbit-card");
  if (!cards.length) return;

  if (reducedMotionQuery.matches) {
    cards.forEach((card) => {
      card.style.setProperty("--orbit-scroll-x", "0px");
      card.style.setProperty("--orbit-scroll-y", "0px");
      card.style.setProperty("--orbit-scroll-rotate", "0deg");
    });
    return;
  }

  const rect = heroOrbitSection.getBoundingClientRect();
  const viewportHeight = window.innerHeight || 1;
  const travel = Math.max(rect.height - viewportHeight * 0.35, viewportHeight * 0.45);
  const progress = Math.max(0, Math.min(1, (-rect.top + viewportHeight * 0.18) / travel));
  const drift = 18 + progress * 24;

  cards.forEach((card, index) => {
    const direction = index % 2 === 0 ? -1 : 1;
    const phase = progress * Math.PI * 1.4 + index * 0.62;
    const x = Math.sin(phase) * drift * (0.75 + index * 0.05) * direction;
    const y = Math.cos(phase) * drift * (0.62 + index * 0.04) + progress * 20;
    const rotate = direction * (progress * 6.5 + index * 0.65);

    card.style.setProperty("--orbit-scroll-x", `${x.toFixed(2)}px`);
    card.style.setProperty("--orbit-scroll-y", `${y.toFixed(2)}px`);
    card.style.setProperty("--orbit-scroll-rotate", `${rotate.toFixed(2)}deg`);
  });
}

