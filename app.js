function buildLightboxAttrs(src, alt = "", caption = "", label = "", kind = "image", poster = "") {
  if (!src) return "";

  const resolvedAlt = alt || caption || "";
  const resolvedCaption = caption || alt || "";
  const resolvedLabel =
    label ||
    (currentLang === "it"
      ? kind === "video"
        ? `Apri video ${resolvedCaption || resolvedAlt || ""}`.trim()
        : `Ingrandisci ${resolvedCaption || resolvedAlt || "immagine"}`
      : kind === "video"
        ? `Open video ${resolvedCaption || resolvedAlt || ""}`.trim()
        : `Zoom ${resolvedCaption || resolvedAlt || "image"}`);

  return ` data-lightbox-src="${escapeAttr(src)}" data-lightbox-alt="${escapeAttr(resolvedAlt)}" data-lightbox-caption="${escapeAttr(resolvedCaption)}" data-lightbox-kind="${escapeAttr(kind)}" data-lightbox-poster="${escapeAttr(poster)}" tabindex="0" role="button" aria-label="${escapeAttr(resolvedLabel)}"`;
}

function resolveLocalized(value, fallback = "") {
  if (value == null) return fallback;
  if (typeof value === "string" || typeof value === "number") return String(value);
  if (Array.isArray(value)) return value.map((item) => resolveLocalized(item, "")).filter(Boolean).join(", ");
  if (typeof value === "object") {
    if (value[currentLang] != null && value[currentLang] !== "") return String(value[currentLang]);
    if (value.it != null && value.it !== "") return String(value.it);
    if (value.en != null && value.en !== "") return String(value.en);
    const first = Object.values(value).find((entry) => entry != null && entry !== "");
    return first != null ? String(first) : fallback;
  }
  return fallback;
}

function syncLightboxLabels() {
  if (!lightboxState.root) return;

  const dialogLabel = currentLang === "it" ? "Anteprima immagine" : "Image preview";
  const closeLabel = currentLang === "it" ? "Chiudi anteprima" : "Close preview";

  if (lightboxState.dialog) {
    lightboxState.dialog.setAttribute("aria-label", dialogLabel);
  }

  if (lightboxState.closeButton) {
    lightboxState.closeButton.setAttribute("aria-label", closeLabel);
  }
}

function ensureLightbox() {
  if (lightboxState.root) return lightboxState.root;

  const root = document.createElement("div");
  root.className = "image-lightbox";
  root.setAttribute("aria-hidden", "true");
  root.innerHTML = `
    <div class="image-lightbox__backdrop" data-lightbox-close></div>
    <div class="image-lightbox__dialog" role="dialog" aria-modal="true" aria-label="Anteprima immagine">
      <button type="button" class="image-lightbox__close" data-lightbox-close aria-label="Chiudi anteprima">×</button>
      <img class="image-lightbox__image" alt="" />
      <video class="image-lightbox__video" playsinline preload="metadata" muted hidden loop></video>
      <p class="image-lightbox__caption" hidden></p>
    </div>
  `;

  document.body.appendChild(root);

  lightboxState.root = root;
  lightboxState.dialog = root.querySelector(".image-lightbox__dialog");
  lightboxState.closeButton = root.querySelector(".image-lightbox__close");
  lightboxState.image = root.querySelector(".image-lightbox__image");
  lightboxState.video = root.querySelector(".image-lightbox__video");
  lightboxState.caption = root.querySelector(".image-lightbox__caption");
  if (lightboxState.caption) lightboxState.caption.hidden = true;

  root.addEventListener("click", (event) => {
    const closeTrigger = event.target instanceof HTMLElement ? event.target.closest("[data-lightbox-close]") : null;
    if (closeTrigger) {
      event.preventDefault();
      closeLightbox();
    }
  });

  return root;
}

function openLightbox(trigger) {
  if (!trigger) return;

  const src = trigger.dataset.lightboxSrc || "";
  if (!src) return;

  const alt = trigger.dataset.lightboxAlt || "";
  const caption = trigger.dataset.lightboxCaption || "";
  const kind = trigger.dataset.lightboxKind || "image";
  const poster = trigger.dataset.lightboxPoster || "";
  const root = ensureLightbox();
  lightboxState.lastFocus = document.activeElement instanceof HTMLElement ? document.activeElement : null;

  if (lightboxState.image) {
    lightboxState.image.hidden = kind === "video";
    if (!kind || kind !== "video") {
      lightboxState.image.src = src;
      lightboxState.image.alt = alt || caption || "";
    } else {
      lightboxState.image.src = "";
      lightboxState.image.alt = "";
    }
  }

  if (lightboxState.video) {
    lightboxState.video.hidden = kind !== "video";
    if (kind === "video") {
      lightboxState.video.src = src;
      lightboxState.video.muted = true;
      lightboxState.video.defaultMuted = true;
      lightboxState.video.volume = 0;
      lightboxState.video.controls = true;
      if (poster) {
        lightboxState.video.poster = poster;
      } else {
        lightboxState.video.removeAttribute("poster");
      }
      lightboxState.video.currentTime = 0;
      lightboxState.video.load();
      lightboxState.video.play().catch(() => {
        // Some browsers may block autoplay on first paint; the controls remain available.
      });
    } else {
      lightboxState.video.pause();
      lightboxState.video.removeAttribute("src");
      lightboxState.video.removeAttribute("poster");
      lightboxState.video.controls = false;
      lightboxState.video.load();
    }
  }

  if (lightboxState.caption) {
    lightboxState.caption.textContent = "";
    lightboxState.caption.hidden = true;
  }

  syncLightboxLabels();
  root.classList.add("is-open");
  root.setAttribute("aria-hidden", "false");
  document.body.classList.add("lightbox-open");

  window.requestAnimationFrame(() => {
    lightboxState.closeButton?.focus();
  });
}

function closeLightbox() {
  if (!lightboxState.root) return;

  lightboxState.root.classList.remove("is-open");
  lightboxState.root.setAttribute("aria-hidden", "true");
  document.body.classList.remove("lightbox-open");

  if (lightboxState.image) {
    lightboxState.image.src = "";
    lightboxState.image.alt = "";
    lightboxState.image.hidden = false;
  }

  if (lightboxState.video) {
    lightboxState.video.pause();
    lightboxState.video.removeAttribute("src");
    lightboxState.video.removeAttribute("poster");
    lightboxState.video.controls = false;
    lightboxState.video.load();
    lightboxState.video.hidden = true;
  }

  if (lightboxState.caption) {
    lightboxState.caption.textContent = "";
    lightboxState.caption.hidden = true;
  }

  const focusTarget = lightboxState.lastFocus;
  lightboxState.lastFocus = null;
  if (focusTarget && typeof focusTarget.focus === "function") {
    focusTarget.focus();
  }
}

