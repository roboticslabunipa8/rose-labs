function normalizeText(value) {
  return String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

function getInitials(item) {
  if (item.initials) return item.initials;
  const name = resolveLocalized(item.name, "").trim();
  if (!name) return "RoSE";
  return name
    .split(/\s+/)
    .slice(0, 3)
    .map((part) => part[0]?.toUpperCase() || "")
    .join("");
}

function getPeopleGroup(item) {
  const role = normalizeText(resolveLocalized(item.role, ""));

  if (role.includes("responsabile") || role.includes("lab lead") || role.includes("professor") || role.includes("lead")) {
    return "lead";
  }

  if (
    role.includes("dottor") ||
    role.includes("phd") ||
    role.includes("post doc") ||
    role.includes("postdoc") ||
    role.includes("researcher")
  ) {
    return "research";
  }

  if (role.includes("bors") || role.includes("fellow") || role.includes("intern") || role.includes("support")) {
    return "fellow";
  }

  return "other";
}

