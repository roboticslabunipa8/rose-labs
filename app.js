function resolveHeroMedia(items) {
  const realItems = (items || [])
    .filter((item) => item && item.src && item.kind !== "video")
    .sort((a, b) => (Number(a.order) || 0) - (Number(b.order) || 0));

  const mediaPool = realItems.length >= 6 ? realItems : [...realItems, ...heroFallbackMedia];
  const seen = new Set();

  return mediaPool.filter((item) => {
    if (!item.src || seen.has(item.src)) return false;
    seen.add(item.src);
    return true;
  });
}

